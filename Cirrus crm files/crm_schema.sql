-- ----------------------------------------------------------------------------
-- VERIFICATION QUERY
-- Demonstrates: INNER JOIN (opportunities->accounts, ->users),
--               LEFT JOIN (activities, since not every deal has one yet),
--               aggregate window function (running rank of deal size
--               within each owner's book, plus a per-owner total via
--               window SUM).
-- ----------------------------------------------------------------------------
SELECT
    o.opportunity_id,
    o.name                                  AS deal_name,
    a.account_name,
    u.first_name || ' ' || u.last_name      AS owner_name,
    o.stage,
    o.amount,
    COUNT(act.activity_id)                  AS activity_count,
    RANK() OVER (
        PARTITION BY o.owner_id
        ORDER BY o.amount DESC
    )                                        AS deal_rank_in_owner_book,
    SUM(o.amount) OVER (
        PARTITION BY o.owner_id
    )                                        AS owner_total_pipeline
FROM crm.opportunities o
INNER JOIN crm.accounts a ON a.account_id = o.account_id
INNER JOIN crm.users u    ON u.user_id    = o.owner_id
LEFT JOIN crm.activities act ON act.opportunity_id = o.opportunity_id
GROUP BY
    o.opportunity_id, o.name, a.account_name, u.first_name, u.last_name,
    o.stage, o.amount, o.owner_id
ORDER BY o.owner_id, deal_rank_in_owner_book;

