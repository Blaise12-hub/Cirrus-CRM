CREATE SCHEMA IF NOT EXISTS crm;
SET search_path TO crm, public;

-- ----------------------------------------------------------------------------
-- 1. UPDATED_AT TRIGGER FUNCTION & TRIGGERS
-- Ensures updated_at is always synchronized automatically on row updates
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION crm.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_teams_updated_at ON crm.teams;
CREATE TRIGGER trg_teams_updated_at
    BEFORE UPDATE ON crm.teams
    FOR EACH ROW EXECUTE FUNCTION crm.set_updated_at();

