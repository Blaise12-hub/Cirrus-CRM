-- ----------------------------------------------------------------------------
-- 4. NOTIFICATIONS (REMINDERS)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm.notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    activity_id     BIGINT,
    type            VARCHAR(50) NOT NULL DEFAULT 'task_reminder', -- 'task_due', 'task_overdue', 'general'
    title           VARCHAR(255) NOT NULL,
    message         TEXT,
    is_read         BOOLEAN NOT NULL DEFAULT FALSE,
    read_at         TIMESTAMPTZ,
    due_date        TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id)
        REFERENCES crm.users (user_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_notifications_activity FOREIGN KEY (activity_id)
        REFERENCES crm.activities (activity_id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_unread
    ON crm.notifications (user_id, is_read, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_activity
    ON crm.notifications (activity_id);

DROP TRIGGER IF EXISTS trg_notifications_updated_at ON crm.notifications;
CREATE TRIGGER trg_notifications_updated_at
    BEFORE UPDATE ON crm.notifications
    FOR EACH ROW EXECUTE FUNCTION crm.set_updated_at();

