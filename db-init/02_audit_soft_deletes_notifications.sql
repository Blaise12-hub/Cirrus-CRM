-- ----------------------------------------------------------------------------
-- 3. AUDIT TRAIL
-- Comprehensive audit logging table and trigger function
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm.audit_logs (
    audit_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name   VARCHAR(80) NOT NULL,
    record_id    BIGINT NOT NULL,
    action       VARCHAR(10) NOT NULL, -- 'INSERT', 'UPDATE', 'DELETE', 'SOFT_DELETE'
    changed_by   BIGINT,               -- user_id (NULL if system/migration)
    old_data     JSONB,
    new_data     JSONB,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_audit_action CHECK (action IN ('INSERT', 'UPDATE', 'DELETE', 'SOFT_DELETE')),
    CONSTRAINT fk_audit_user FOREIGN KEY (changed_by)
        REFERENCES crm.users (user_id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_audit_table_record ON crm.audit_logs (table_name, record_id);
CREATE INDEX IF NOT EXISTS idx_audit_changed_by ON crm.audit_logs (changed_by);
CREATE INDEX IF NOT EXISTS idx_audit_created_at ON crm.audit_logs (created_at DESC);

CREATE OR REPLACE FUNCTION crm.audit_log_trigger()
RETURNS TRIGGER AS $$
DECLARE
    v_record_id BIGINT;
    v_user_id BIGINT := NULL;
    v_old_data JSONB := NULL;
    v_new_data JSONB := NULL;
    v_action VARCHAR(15);
BEGIN
    BEGIN
        v_user_id := NULLIF(current_setting('crm.current_user_id', true), '')::BIGINT;
    EXCEPTION WHEN OTHERS THEN
        v_user_id := NULL;
    END;

    IF (TG_OP = 'DELETE') THEN
        v_action := 'DELETE';
        v_old_data := to_jsonb(OLD);
        v_record_id := COALESCE(
            (v_old_data->>'account_id')::BIGINT,
            (v_old_data->>'contact_id')::BIGINT,
            (v_old_data->>'lead_id')::BIGINT,
            (v_old_data->>'opportunity_id')::BIGINT,
            (v_old_data->>'activity_id')::BIGINT,
            (v_old_data->>'user_id')::BIGINT
        );
        IF v_user_id IS NULL AND v_old_data ? 'owner_id' THEN
            v_user_id := (v_old_data->>'owner_id')::BIGINT;
        END IF;

        INSERT INTO crm.audit_logs (table_name, record_id, action, changed_by, old_data, new_data)
        VALUES (TG_TABLE_NAME, v_record_id, v_action, v_user_id, v_old_data, NULL);
        RETURN OLD;

    ELSIF (TG_OP = 'UPDATE') THEN
        v_old_data := to_jsonb(OLD);
        v_new_data := to_jsonb(NEW);
        v_record_id := COALESCE(
            (v_new_data->>'account_id')::BIGINT,
            (v_new_data->>'contact_id')::BIGINT,
            (v_new_data->>'lead_id')::BIGINT,
            (v_new_data->>'opportunity_id')::BIGINT,
            (v_new_data->>'activity_id')::BIGINT,
            (v_new_data->>'user_id')::BIGINT
        );
        IF (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL) THEN
            v_action := 'SOFT_DELETE';
        ELSE
            v_action := 'UPDATE';
        END IF;

        IF v_user_id IS NULL AND v_new_data ? 'owner_id' THEN
            v_user_id := (v_new_data->>'owner_id')::BIGINT;
        END IF;

        INSERT INTO crm.audit_logs (table_name, record_id, action, changed_by, old_data, new_data)
        VALUES (TG_TABLE_NAME, v_record_id, v_action, v_user_id, v_old_data, v_new_data);
        RETURN NEW;

    ELSIF (TG_OP = 'INSERT') THEN
        v_action := 'INSERT';
        v_new_data := to_jsonb(NEW);
        v_record_id := COALESCE(
            (v_new_data->>'account_id')::BIGINT,
            (v_new_data->>'contact_id')::BIGINT,
            (v_new_data->>'lead_id')::BIGINT,
            (v_new_data->>'opportunity_id')::BIGINT,
            (v_new_data->>'activity_id')::BIGINT,
            (v_new_data->>'user_id')::BIGINT
        );
        IF v_user_id IS NULL AND v_new_data ? 'owner_id' THEN
            v_user_id := (v_new_data->>'owner_id')::BIGINT;
        END IF;

        INSERT INTO crm.audit_logs (table_name, record_id, action, changed_by, old_data, new_data)
        VALUES (TG_TABLE_NAME, v_record_id, v_action, v_user_id, NULL, v_new_data);
        RETURN NEW;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audit_accounts ON crm.accounts;
CREATE TRIGGER trg_audit_accounts
    AFTER INSERT OR UPDATE OR DELETE ON crm.accounts
    FOR EACH ROW EXECUTE FUNCTION crm.audit_log_trigger();

